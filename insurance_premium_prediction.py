import pandas as pd

# Upload CSV file via Google Colab's file upload widget
from google.colab import files
uploaded = files.upload()

# Read the uploaded CSV file into a pandas DataFrame
df = pd.read_csv('insurance.csv')

# Count occurrences of each unique value in the 'smoker' column
df.smoker.value_counts()

# Count occurrences of each unique value in the 'region' column
df.region.value_counts()

# Convert 'sex' column to binary: 1 if male, 0 if female
df['sex'] = df['sex'].apply(lambda x: 1 if x == 'male' else 0)

# Convert 'smoker' column to binary: 1 if yes, 0 if no
df['smoker'] = df['smoker'].apply(lambda x: 1 if x == 'yes' else 0)

# One-hot encode the 'region' column and drop the original column
df = df.join(pd.get_dummies(df.region, dtype=int)).drop('region', axis=1)

# Show the DataFrame with the new changes
df

# Display histograms for each column
df.hist(figsize=(15,10))

# Display concise summary of the DataFrame including datatypes
df.info()

import matplotlib.pyplot as plt
import seaborn as sns

# Plot a heatmap of the correlation matrix
plt.figure(figsize=(15,10))
sns.heatmap(df.corr(), annot=True, cmap = 'coolwarm', vmin = -1, vmax =1)

from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import root_mean_squared_error, mean_absolute_error

# Split data into features and target
X = df.drop('charges', axis=1)
y = df['charges']

# Split dataset into training and testing sets
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2)

# Initialize and train a Random Forest Regressor model
model = RandomForestRegressor(n_jobs=-1)
model.fit(X_train, y_train)

# Evaluate model accuracy on the test set
model.score(X_test, y_test)

# Predict charges using the test set
y_pred = model.predict(X_test)

# Calculate Root Mean Squared Error
rmse = root_mean_squared_error(y_test, y_pred)

rmse

# Standard deviation of original charges
df.charges.std()

# Standard deviation of test set charges
y_test.std()

# Median of original charges
df.charges.median()

# Calculate Mean Absolute Error
mae = mean_absolute_error(y_pred, y_test)

mae

